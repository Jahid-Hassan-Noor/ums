logger = logging.getLogger(__name__)

BACKUP_JSON_FILENAME = "database.json"
BACKUP_SQL_FILENAME = "database.sql"
BACKUP_MANIFEST_FILENAME = "manifest.json"
BACKUP_RESTORE_FILENAME = "RESTORE.md"
BACKUP_MEDIA_PREFIX = "media"
SQL_BACKUP_MARKER = "-- UMS SQL Backup"
BACKUP_SETTINGS_KEY = "ums.backup_restore"

DEFAULT_BACKUP_SETTINGS = {
    "monthly_email_enabled": False,
    "recipients": [],
}


@dataclass(frozen=True)
class BackupArtifact:
    path: Path
    filename: str
    created_at: str


@dataclass(frozen=True)
class RestoreResult:
    restored_at: str
    manifest: dict
    media_files_restored: int
    database_format: str


def _iter_media_files(media_root):
    root = Path(media_root)
    if not root.exists():
        return

    for path in root.rglob("*"):
        if path.is_symlink() or not path.is_file():
            continue
        yield path


def _write_database_fixture(output_path):
    with Path(output_path).open("w", encoding="utf-8") as output:
        call_command(
            "dumpdata",
            "--natural-foreign",
            "--natural-primary",
            "--indent",
            "2",
            stdout=output,
        )


def _database_connection_config():
    config = settings.DATABASES["default"]
    return {
        "name": str(config.get("NAME") or ""),
        "user": str(config.get("USER") or ""),
        "password": str(config.get("PASSWORD") or ""),
        "host": str(config.get("HOST") or "127.0.0.1"),
        "port": str(config.get("PORT") or "5432"),
        "engine": str(config.get("ENGINE") or ""),
    }


def _postgres_command_env(config):
    if not config["password"]:
        return None
    return {"PGPASSWORD": config["password"]}


def _run_postgres_command(command, *, env=None, stdout=None):
    process_env = None
    if env:
        process_env = os.environ.copy()
        process_env.update(env)

    try:
        subprocess.run(
            command,
            check=True,
            env=process_env,
            stdout=stdout,
            stderr=subprocess.PIPE,
            text=True,
        )
    except FileNotFoundError as exc:
        raise RuntimeError(
            "PostgreSQL client tools are not installed in the backend container."
        ) from exc
    except subprocess.CalledProcessError as exc:
        detail = (exc.stderr or "").strip()
        message = "PostgreSQL command failed."
        if detail:
            message = f"{message} {detail}"
        raise RuntimeError(message) from exc


def _write_database_sql_dump(output_path):
    config = _database_connection_config()
    if "postgresql" not in config["engine"]:
        raise RuntimeError("SQL backups are only supported for PostgreSQL databases.")

    command = [
        "pg_dump",
        "--host",
        config["host"],
        "--port",
        config["port"],
        "--username",
        config["user"],
        "--dbname",
        config["name"],
        "--format=plain",
        "--clean",
        "--if-exists",
        "--no-owner",
        "--no-privileges",
        "--quote-all-identifiers",
        "--encoding=UTF8",
    ]

    with Path(output_path).open("w", encoding="utf-8") as output:
        output.write(f"{SQL_BACKUP_MARKER}\n")
        output.write("-- Generated by the UMS admin backup tool.\n\n")
        output.flush()
        _run_postgres_command(
            command,
            env=_postgres_command_env(config),
            stdout=output,
        )


def _validate_sql_backup_file(sql_path):
    path = Path(sql_path)
    try:
        header = path.read_text(encoding="utf-8", errors="ignore")[:4096]
    except OSError as exc:
        raise ValueError("SQL backup file could not be read.") from exc

    if SQL_BACKUP_MARKER not in header:
        raise ValueError("SQL backup must be generated by the UMS backup tool.")


def _restore_database_sql(sql_path):
    _validate_sql_backup_file(sql_path)
    config = _database_connection_config()
    if "postgresql" not in config["engine"]:
        raise ValueError("SQL restore is only supported for PostgreSQL databases.")

    command = [
        "psql",
        "--host",
        config["host"],
        "--port",
        config["port"],
        "--username",
        config["user"],
        "--dbname",
        config["name"],
        "--set",
        "ON_ERROR_STOP=1",
        "--single-transaction",
        "--file",
        str(sql_path),
    ]
    connections.close_all()
    try:
        _run_postgres_command(command, env=_postgres_command_env(config))
    finally:
        connections.close_all()


def _read_manifest(archive):
    if BACKUP_MANIFEST_FILENAME not in archive.namelist():
        return {}

    try:
        with archive.open(BACKUP_MANIFEST_FILENAME) as manifest_file:
            data = json.loads(manifest_file.read().decode("utf-8"))
    except (json.JSONDecodeError, UnicodeDecodeError, OSError):
        return {}

    return data if isinstance(data, dict) else {}


def _validate_media_member(member):
    if member.is_dir() or not member.filename.startswith(f"{BACKUP_MEDIA_PREFIX}/"):
        return None

    relative_name = member.filename[len(BACKUP_MEDIA_PREFIX) + 1 :]
    if not relative_name:
        return None

    relative_path = Path(relative_name)
    if relative_path.is_absolute() or ".." in relative_path.parts:
        raise ValueError(f"Unsafe media path in backup archive: {member.filename}")

    return relative_path


def validate_backup_archive(archive_path):
    path = Path(archive_path)
    if not path.exists():
        raise ValueError("Backup archive was not uploaded.")

    if not zipfile.is_zipfile(path):
        raise ValueError("Backup archive must be a valid UMS .zip file.")

    with zipfile.ZipFile(path) as archive:
        names = set(archive.namelist())
        if BACKUP_SQL_FILENAME not in names and BACKUP_JSON_FILENAME not in names:
            raise ValueError(
                f"Backup archive is missing {BACKUP_SQL_FILENAME} or {BACKUP_JSON_FILENAME}."
            )

        if BACKUP_SQL_FILENAME in names:
            with tempfile.TemporaryDirectory(prefix="ums-sql-validate-") as work_dir:
                sql_path = Path(work_dir) / BACKUP_SQL_FILENAME
                with archive.open(BACKUP_SQL_FILENAME) as source, sql_path.open("wb") as target:
                    shutil.copyfileobj(source, target)
                _validate_sql_backup_file(sql_path)

        for member in archive.infolist():
            _validate_media_member(member)

        return _read_manifest(archive)


def _restore_media_from_archive(archive):
    media_root = Path(settings.MEDIA_ROOT)
    media_root.mkdir(parents=True, exist_ok=True)
    restored_count = 0

    for member in archive.infolist():
        relative_path = _validate_media_member(member)
        if relative_path is None:
            continue

        destination = media_root / relative_path
        destination.parent.mkdir(parents=True, exist_ok=True)
        with archive.open(member) as source, destination.open("wb") as target:
            shutil.copyfileobj(source, target)
        restored_count += 1

    return restored_count


def _preserve_manual_maintenance_mode():
    try:
        record = SystemSetting.objects.filter(key=setting_key("security")).first()
        values = dict(record.value) if record and isinstance(record.value, dict) else {}
        values["maintenance_mode"] = True
        SystemSetting.objects.update_or_create(
            key=setting_key("security"),
            defaults={
                "value": values,
                "description": "High-impact access policies. Administrators retain access to settings and audit logs.",
            },
        )
        invalidate_settings_cache()
    except DatabaseError:
        logger.exception("Unable to preserve manual maintenance mode after restore.")


def _require_manual_maintenance_for_restore():
    invalidate_settings_cache()
    if not maintenance_mode_enabled():
        raise ValueError("Turn on maintenance mode manually before restoring a backup.")


def restore_database_backup_archive(
    archive_path,
    *,
    skip_media=False,
    no_flush=False,
    require_maintenance=True,
    verbosity=1,
):
    if require_maintenance:
        _require_manual_maintenance_for_restore()

    manifest = validate_backup_archive(archive_path)
    restored_at = timezone.now()
    media_files_restored = 0
    database_format = "json"
    preserve_maintenance = require_maintenance

    try:
        with zipfile.ZipFile(archive_path) as archive:
            with tempfile.TemporaryDirectory(prefix="ums-restore-") as work_dir:
                names = set(archive.namelist())
                if BACKUP_SQL_FILENAME in names:
                    sql_path = Path(work_dir) / BACKUP_SQL_FILENAME
                    with archive.open(BACKUP_SQL_FILENAME) as source, sql_path.open("wb") as target:
                        shutil.copyfileobj(source, target)
                    _restore_database_sql(sql_path)
                    database_format = "sql"
                else:
                    database_path = Path(work_dir) / BACKUP_JSON_FILENAME
                    with archive.open(BACKUP_JSON_FILENAME) as source, database_path.open("wb") as target:
                        shutil.copyfileobj(source, target)

                    call_command("migrate", interactive=False, verbosity=verbosity)
                    if not no_flush:
                        call_command("flush", interactive=False, verbosity=verbosity)
                    call_command("loaddata", str(database_path), verbosity=verbosity)

                if not skip_media:
                    media_files_restored = _restore_media_from_archive(archive)
    except Exception:
        if preserve_maintenance:
            _preserve_manual_maintenance_mode()
        raise

    if preserve_maintenance:
        _preserve_manual_maintenance_mode()

    return RestoreResult(
        restored_at=restored_at.isoformat(),
        manifest=manifest,
        media_files_restored=media_files_restored,
        database_format=database_format,
    )


def restore_database_backup_file(backup_path, *, original_name=None, **kwargs):
    name = str(original_name or backup_path).lower()
    suffix = Path(name).suffix

    if suffix == ".sql":
        if kwargs.get("require_maintenance", True):
            _require_manual_maintenance_for_restore()
        try:
            _restore_database_sql(backup_path)
        except Exception:
            if kwargs.get("require_maintenance", True):
                _preserve_manual_maintenance_mode()
            raise
        if kwargs.get("require_maintenance", True):
            _preserve_manual_maintenance_mode()
        return RestoreResult(
            restored_at=timezone.now().isoformat(),
            manifest={"backup_type": "postgresql_sql"},
            media_files_restored=0,
            database_format="sql",
        )

    return restore_database_backup_archive(backup_path, **kwargs)


def _restore_readme(filename):
    return f"""# UMS Backup Restore

This archive was generated by the UMS admin backup tool.

Contents:
- `{BACKUP_SQL_FILENAME}`: PostgreSQL SQL dump. This is the preferred restore format for VPS migrations when PostgreSQL client tools are available.
- `{BACKUP_JSON_FILENAME}`: Django JSON fixture fallback.
- `{BACKUP_MEDIA_PREFIX}/`: uploaded media files from MEDIA_ROOT.
- `{BACKUP_MANIFEST_FILENAME}`: metadata about the backup.

Dashboard restore:
1. Turn on maintenance mode manually from Admin Settings.
2. Open Admin -> Backup and Restore.
3. Upload `{filename}` and confirm the restore.
4. Verify login, dashboards, records, uploaded media, and public pages before turning maintenance mode off manually.

CLI fallback:

```bash
python manage.py restore_ums_backup {filename} --confirm
```
"""


def build_database_backup_archive(user=None):
    created_at = timezone.now()
    timestamp = created_at.strftime("%Y%m%d-%H%M%SZ")
    filename = f"ums-backup-{timestamp}.zip"

    archive_handle = tempfile.NamedTemporaryFile(
        prefix="ums-backup-",
        suffix=".zip",
        delete=False,
    )
    archive_path = Path(archive_handle.name)
    archive_handle.close()

    try:
        with tempfile.TemporaryDirectory(prefix="ums-backup-work-") as work_dir:
            json_database_path = Path(work_dir) / BACKUP_JSON_FILENAME
            sql_database_path = Path(work_dir) / BACKUP_SQL_FILENAME
            _write_database_fixture(json_database_path)

            sql_backup_warning = ""
            try:
                _write_database_sql_dump(sql_database_path)
            except RuntimeError as exc:
                sql_backup_warning = str(exc)
                sql_database_path.unlink(missing_ok=True)

            media_root = Path(getattr(settings, "MEDIA_ROOT", ""))
            media_files = list(_iter_media_files(media_root))
            media_bytes = 0
            for path in media_files:
                try:
                    media_bytes += path.stat().st_size
                except OSError:
                    continue

            database_formats = ["json"]
            if sql_database_path.exists():
                database_formats.insert(0, "sql")

            manifest = {
                "app": "UMS",
                "backup_type": "postgresql_sql_with_json_and_media",
                "backup_version": 1,
                "created_at": created_at.isoformat(),
                "database_engine": settings.DATABASES["default"].get("ENGINE", ""),
                "database_name": settings.DATABASES["default"].get("NAME", ""),
                "database_formats": database_formats,
                "generated_by": getattr(user, "username", "") or "",
                "maintenance_mode_enabled": maintenance_mode_enabled(),
                "maintenance_mode_changed": False,
                "media_file_count": len(media_files),
                "media_total_bytes": media_bytes,
                "restore_command": "python manage.py restore_ums_backup <backup.zip> --confirm",
            }
            if sql_backup_warning:
                manifest["sql_backup_warning"] = sql_backup_warning

            with zipfile.ZipFile(
                archive_path,
                mode="w",
                compression=zipfile.ZIP_DEFLATED,
                compresslevel=6,
            ) as archive:
                if sql_database_path.exists():
                    archive.write(sql_database_path, BACKUP_SQL_FILENAME)
                archive.write(json_database_path, BACKUP_JSON_FILENAME)
                archive.writestr(BACKUP_MANIFEST_FILENAME, json.dumps(manifest, indent=2))
                archive.writestr(BACKUP_RESTORE_FILENAME, _restore_readme(filename))

                for media_file in media_files:
                    try:
                        relative_path = media_file.relative_to(media_root).as_posix()
                    except ValueError:
                        continue
                    archive.write(media_file, f"{BACKUP_MEDIA_PREFIX}/{relative_path}")
    except Exception:
        archive_path.unlink(missing_ok=True)
        raise

    return BackupArtifact(
        path=archive_path,
        filename=filename,
        created_at=created_at.isoformat(),
    )


def _normalize_recipients(raw_recipients):
    if raw_recipients in (None, ""):
        return []
    if not isinstance(raw_recipients, list):
        raise ValidationError({"recipients": "Provide recipients as a list of email addresses."})

    recipients = []
    seen = set()
    for raw_email in raw_recipients:
        email = str(raw_email or "").strip()
        if not email:
            continue
        try:
            validate_email(email)
        except ValidationError:
            raise ValidationError({"recipients": f"{email} is not a valid email address."}) from None
        key = email.lower()
        if key in seen:
            continue
        seen.add(key)
        recipients.append(email)

    if len(recipients) > 20:
        raise ValidationError({"recipients": "Use 20 backup recipient addresses or fewer."})
    return recipients


def get_database_backup_settings():
    try:
        record = SystemSetting.objects.filter(key=BACKUP_SETTINGS_KEY).first()
    except DatabaseError:
        return dict(DEFAULT_BACKUP_SETTINGS)

    values = dict(DEFAULT_BACKUP_SETTINGS)
    if record and isinstance(record.value, dict):
        values.update(
            {
                "monthly_email_enabled": bool(record.value.get("monthly_email_enabled", False)),
                "recipients": _normalize_recipients(record.value.get("recipients", [])),
            }
        )
    return values


def validate_database_backup_settings(submitted):
    if not isinstance(submitted, dict):
        raise ValidationError({"values": "Backup settings values must be an object."})

    current = get_database_backup_settings()
    normalized = dict(current)

    if "monthly_email_enabled" in submitted:
        value = submitted["monthly_email_enabled"]
        if not isinstance(value, bool):
            raise ValidationError({"monthly_email_enabled": "Provide true or false."})
        normalized["monthly_email_enabled"] = value

    if "recipients" in submitted:
        normalized["recipients"] = _normalize_recipients(submitted["recipients"])

    return normalized


def save_database_backup_settings(submitted, *, updated_by=None):
    normalized = validate_database_backup_settings(submitted)
    SystemSetting.objects.update_or_create(
        key=BACKUP_SETTINGS_KEY,
        defaults={
            "value": normalized,
            "description": "Monthly database backup email settings.",
            "updated_by": updated_by,
        },
    )
    return normalized


def send_monthly_backup_email():
    config = get_database_backup_settings()
    recipients = config["recipients"]
    if not config["monthly_email_enabled"]:
        return {"sent": False, "reason": "monthly_email_disabled", "recipients": 0}
    if not recipients:
        return {"sent": False, "reason": "no_recipients", "recipients": 0}

    artifact = build_database_backup_archive(user=None)
    subject_date = timezone.localtime(timezone.now()).strftime("%Y-%m-%d")
    email = EmailMessage(
        subject=f"UMS monthly database backup - {subject_date}",
        body=(
            "Attached is the UMS database and media backup generated by the "
            "scheduled monthly backup job."
        ),
        from_email=getattr(settings, "DEFAULT_FROM_EMAIL", None),
        to=recipients,
    )
    try:
        email.attach(
            artifact.filename,
            artifact.path.read_bytes(),
            "application/zip",
        )
        sent_count = email.send(fail_silently=False)
    finally:
        artifact.path.unlink(missing_ok=True)

    return {
        "sent": bool(sent_count),
        "recipients": len(recipients),
        "filename": artifact.filename,
        "created_at": artifact.created_at,
    }
